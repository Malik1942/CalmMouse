// Reading an Apple .strings file, and writing the module the website imports. Shared by
// scripts/sync-app-strings.mjs and test/i18n.test.js, so the two can't disagree.

const unescape = (s) => s.replace(/\\(.)/g, (_, c) => ({ n: "\n", t: "\t" })[c] ?? c);

/** { english: translation } from the text of a Localizable.strings file. */
export function parseStrings(text) {
  const out = {};
  for (const m of text.matchAll(/^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";/gm)) out[unescape(m[1])] = unescape(m[2]);
  return out;
}

export function stringsModule(map) {
  const keys = Object.keys(map).sort();
  const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`).join("\n");
  return (
    "// Generated by scripts/sync-app-strings.mjs from the app's Resources/zh-Hans.lproj/Localizable.strings.\n" +
    "// Don't edit: change the app's strings and run the script again.\n" +
    `export const APP_ZH = {\n${body}\n};\n`
  );
}
